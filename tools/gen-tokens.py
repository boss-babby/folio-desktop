#!/usr/bin/env python3
"""Generate folio-ui/include/folio/ui/Tokens.h from design-tokens.json.

design-tokens.json is the single source of truth for every colour, duration,
radius and size in the product. This script turns it into a constexpr C++
header so that:

  * a designer changing a token changes the app, with no C++ edit;
  * cmake/ScanHardcodedTokens.cmake can forbid literal colours and durations
    in folio-ui/ sources, because there is now a legitimate place for them;
  * the same JSON can later emit Tokens.qml for a Qt backend without the
    values drifting apart.

Run: python3 tools/gen-tokens.py
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "design-tokens.json"
OUT = ROOT / "folio-ui" / "include" / "folio" / "ui" / "Tokens.h"

# Keys of color.light / color.dark, in declaration order.
PALETTE_KEYS = [
    "bg", "card", "text", "muted", "border", "divider", "accent", "accentSoft",
    "accentText", "surfaceSunken", "hover", "danger", "shadow", "ring", "pageShadow",
]


def parse_color(v: str) -> tuple[int, int, int, int]:
    """'#RRGGBB' or 'rgba(r,g,b,a)' -> (r, g, b, a) with a in 0..255."""
    v = v.strip()
    if v.startswith("#"):
        h = v[1:]
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)
    m = re.match(r"rgba?\(([^)]*)\)", v)
    if not m:
        raise ValueError(f"unparseable colour: {v!r}")
    parts = [p.strip() for p in m.group(1).split(",")]
    r, g, b = (int(float(p)) for p in parts[:3])
    a = round(float(parts[3]) * 255) if len(parts) > 3 else 255
    return (r, g, b, a)


def cfmt(v: str) -> str:
    r, g, b, a = parse_color(v)
    return f"Color{{{r}, {g}, {b}, {a}}}"


def ident(s: str) -> str:
    """JSON key -> valid C++ identifier."""
    s = re.sub(r"[^0-9A-Za-z_]", "_", s)
    return ("k" + s) if s[0].isdigit() else s


_N = r"(-?[\d.]+)(?:px)?"  # a length; the unit is optional because CSS allows
                           # a bare 0, and the prototype writes "0 6px 28px".
SHADOW_RE = re.compile(
    rf"{_N}\s+{_N}\s+{_N}(?:\s+{_N})?\s+\{{(\w+)\}}"
)


def parse_elevation(spec: str) -> list[tuple[float, float, float, float, str]]:
    """'0 6px 28px {shadow}, 0 0 0 1px {ring}' -> [(dx,dy,blur,spread,ref), ...]

    CSS allows the leading 0 to be unitless, and the spread to be absent, so
    both shapes have to be tolerated. Anything that does not match is a token
    authoring error and must fail loudly rather than silently render nothing.
    """
    spec = spec.replace("drop-shadow(", "").replace(")", "")
    out = []
    for part in re.split(r",(?![^(]*\))", spec):
        part = part.strip()
        if not part:
            continue
        m = SHADOW_RE.search(part)
        if not m:
            raise ValueError(f"unparseable shadow layer: {part!r} in {spec!r}")
        dx, dy, blur, spread, ref = m.groups()
        out.append((float(dx), float(dy), float(blur), float(spread or 0), ref))
    if not out:
        raise ValueError(f"no shadow layers found in {spec!r}")
    return out


def main() -> int:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    L = []
    w = L.append

    w("// AUTOGENERATED BY tools/gen-tokens.py -- DO NOT EDIT BY HAND.")
    w("// Source of truth: design-tokens.json")
    w("//")
    w("// Edit the JSON and re-run the generator. CI regenerates this file and")
    w("// fails if the working copy differs, so a hand edit cannot survive.")
    w("")
    w("#pragma once")
    w("")
    w('#include "folio/render/IPaintTarget.h"')
    w("")
    w("#include <array>")
    w("#include <cstdint>")
    w("")
    w("namespace folio::ui::tokens {")
    w("")
    w("using folio::render::Color;")
    w("using folio::render::Corners;")
    w("using folio::render::Shadow;")
    w("")

    # ---- palette -----------------------------------------------------------
    w("/// Every colour that flips between light and dark mode. Widgets take a")
    w("/// `const Palette&` rather than reading a global, so the theme cross-fade")
    w("/// can paint the same widget twice with two different palettes.")
    w("struct Palette {")
    for k in PALETTE_KEYS:
        w(f"    Color {k};")
    w("    /// True past the midpoint of a theme cross-fade. A hard boolean:")
    w("    /// anything that must move smoothly through a transition should")
    w("    /// use darkness() below instead, not this.")
    w("    bool isDark = false;")
    w("};")
    w("")
    w("/// 0 for a white background, 1 for a black one. Continuous across a")
    w("/// theme cross-fade because it reads the already-interpolated colour,")
    w("/// so code that used to branch on isDark can lerp on this and stop")
    w("/// popping at the halfway point.")
    w("[[nodiscard]] inline float darkness(const Palette& p) noexcept {")
    w("    const float lum = (0.299f * static_cast<float>(p.bg.r) +")
    w("                       0.587f * static_cast<float>(p.bg.g) +")
    w("                       0.114f * static_cast<float>(p.bg.b)) /")
    w("                      255.f;")
    w("    return 1.f - lum;")
    w("}")
    w("")
    for scheme in ("light", "dark"):
        src = d["color"][scheme]
        w(f"inline constexpr Palette k{scheme.capitalize()}{{")
        for k in PALETTE_KEYS:
            w(f"    /* {k:14} */ {cfmt(src[k])},")
        w(f"    /* isDark */ {'true' if scheme == 'dark' else 'false'},")
        w("};")
        w("")

    # ---- scheme-independent colours ---------------------------------------
    w("/// Colours that do not flip with the theme (brand/semantic constants).")
    w("namespace fixed {")
    for k, v in d["color"]["fixed"].items():
        w(f"inline constexpr Color {ident(k)} = {cfmt(v)};")
    w("}  // namespace fixed")
    w("")
    w("namespace highlighter {")
    for k, v in d["color"]["highlighter"].items():
        w(f"inline constexpr Color {ident(k)} = {cfmt(v)};")
    arr = ", ".join(ident(k) for k in d["color"]["highlighter"])
    w(f"inline constexpr std::array<Color, {len(d['color']['highlighter'])}> kAll{{{arr}}};")
    w("}  // namespace highlighter")
    w("")
    for grp in ("inkPalette", "docAccent"):
        vals = ", ".join(cfmt(c) for c in d["color"][grp])
        w(f"inline constexpr std::array<Color, {len(d['color'][grp])}> {grp}{{{vals}}};")
    w("")

    # ---- page themes -------------------------------------------------------
    w("/// Paper/ink pairs fed to the page-theme colour filter (never a re-render).")
    w("struct PageThemeTokens { Color paper, ink; };")
    for k, v in d["pageTheme"].items():
        w(f"inline constexpr PageThemeTokens pageTheme_{ident(k)}{{{cfmt(v['paper'])}, {cfmt(v['ink'])}}};")
    w("")

    # ---- scalar groups -----------------------------------------------------
    def emit_scalars(group: str, data: dict, typ: str, suffix: str = "f") -> None:
        # A JSON integer must still be emitted with a decimal point: "6f" is
        # not a valid C++ literal, "6.0f" is.
        def lit(v):
            return f"{float(v)!r}{suffix}" if typ == "float" else f"{v}{suffix}"

        w(f"namespace {group} {{")
        for k, v in data.items():
            if isinstance(v, dict):
                w(f"namespace {ident(k)} {{")
                for k2, v2 in v.items():
                    if isinstance(v2, (int, float)) and not isinstance(v2, bool):
                        w(f"inline constexpr {typ} {ident(k2)} = {lit(v2)};")
                w(f"}}  // namespace {ident(k)}")
            elif isinstance(v, (int, float)) and not isinstance(v, bool):
                w(f"inline constexpr {typ} {ident(k)} = {lit(v)};")
        w(f"}}  // namespace {group}")
        w("")

    emit_scalars("radius", d["radius"], "float")
    emit_scalars("space", d["spacing"], "float")
    emit_scalars("size", d["size"], "float")
    emit_scalars("icon", {k: v for k, v in d["icon"].items() if isinstance(v, (int, float))}, "float")

    # durations are integers in milliseconds
    w("/// Animation durations in milliseconds, straight from the prototype's CSS.")
    w("namespace dur {")
    for k, v in d["motion"]["duration"].items():
        w(f"inline constexpr int {ident(k)} = {int(v)};")
    w("}  // namespace dur")
    w("")
    w("namespace delay {")
    for k, v in d["motion"]["delay"].items():
        w(f"inline constexpr int {ident(k)} = {int(v)};")
    for k, v in d["motion"]["autoDismiss"].items():
        w(f"inline constexpr int autoDismiss_{ident(k)} = {int(v)};")
    w("}  // namespace delay")
    w("")

    bez = d["motion"]["easing"]["standard"]["bezier"]
    w("/// The prototype uses exactly one easing curve everywhere:")
    w(f"///   {d['motion']['easing']['standard']['css']}")
    w("inline constexpr float kEaseStandard[4] = {"
      + ", ".join(f"{float(x)}f" for x in bez) + "};")
    w("")

    # ---- typography --------------------------------------------------------
    w("struct TypeScale {")
    w("    float size;")
    w("    int weight;")
    w("    float letterSpacingEm;")
    w("    bool uppercase;")
    w("};")
    for k, v in d["typography"]["scale"].items():
        ls = v.get("letterSpacing", "0")
        ls = float(str(ls).replace("em", "")) if "em" in str(ls) else float(ls)
        up = "true" if v.get("transform") == "uppercase" else "false"
        w(f"inline constexpr TypeScale type_{ident(k)}{{{float(v['size'])}f, {v['weight']}, {ls}f, {up}}};")
    w("")

    # ---- elevation ---------------------------------------------------------
    w("/// Elevations are composed of up to two shadow layers whose colour comes")
    w("/// from the active palette, so they are functions, not constants.")
    w("struct Elevation {")
    w("    std::array<Shadow, 2> layers{};")
    w("    int count = 0;")
    w("};")
    w("")
    w("namespace elevation {")
    for k, spec in d["elevation"].items():
        layers = parse_elevation(spec)
        w(f"/// {spec}")
        w(f"[[nodiscard]] inline Elevation {ident(k)}(const Palette& p) noexcept {{")
        w("    Elevation e;")
        for i, (dx, dy, blur, spread, ref) in enumerate(layers):
            if ref in PALETTE_KEYS:
                col = f"p.{ref}"
            else:
                col = f"fixed::{ident(ref)}"
            w(f"    e.layers[{i}] = Shadow{{{dx}f, {dy}f, {blur}f, {spread}f, {col}}};")
        w(f"    e.count = {len(layers)};")
        w("    return e;")
        w("}")
    w("}  // namespace elevation")
    w("")

    # ---- performance -------------------------------------------------------
    w("namespace perf {")
    for k, v in d["performance"].items():
        if isinstance(v, dict):
            w(f"namespace {ident(k)} {{")
            for k2, v2 in v.items():
                big = isinstance(v2, int) and v2 > 100000
                if big:
                    w(f"inline constexpr std::uint64_t {ident(k2)} = {v2}ull;")
                else:
                    w(f"inline constexpr float {ident(k2)} = {float(v2)!r}f;")
            w(f"}}  // namespace {ident(k)}")
        elif isinstance(v, (int, float)):
            w(f"inline constexpr float {ident(k)} = {float(v)}f;")
    w("}  // namespace perf")
    w("")
    w("}  // namespace folio::ui::tokens")
    w("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(L)
    previous = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    OUT.write_text(text, encoding="utf-8")
    status = "unchanged" if previous == text else ("written" if previous else "created")
    print(f"{OUT.relative_to(ROOT)}: {status}, {len(L)} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
